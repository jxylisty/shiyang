const HAS_LATIN = /[A-Za-z]{3,}/

/**
 * 归一化单味药材展示数据：
 * - 若库内已是中文功效，直接拆词返回；
 * - 若库内为 HERB 英文原文或为空，优先补充药典中文功效，并把 HERB 英文拆为 { enFunc, enIndic } 供折叠查阅。
 */
export function normalizeHerbView(h) {
  if (!h) return null
  const sup = PHARMACOPOEIA_FUNCTIONS[h.name] || {}
  const rawFn = (h.functions || '').trim()
  const isEn = HAS_LATIN.test(rawFn)

  let cnFn = !isEn && rawFn ? rawFn : (sup.fn || '')
  // 出处标注：库内若是英文/空，用的必然是本文档的 sup.fn；库内若已是中文，
  // 还要再分两种情况——文本与 sup.fn 完全相同（说明就是本表回填进库的，
  // 见 scripts/backfill_pharmacopoeia_herb.py）仍要标典籍；否则是原始整理的中文功效，不标。
  let cnSrc = ''
  if (!isEn && rawFn) {
    cnSrc = (sup.fn && rawFn === sup.fn) ? (sup.src || '') : ''
  } else {
    cnSrc = sup.src || ''
  }

  let enFunc = ''
  let enIndic = ''
  if (isEn) {
    const parts = rawFn.split(/\s*\|\s*Indication:\s*/i)
    if (parts.length > 1) {
      enFunc = parts[0].trim()
      enIndic = parts.slice(1).join(' ').trim()
    } else if (/^Indication:/i.test(rawFn)) {
      enIndic = rawFn.replace(/^Indication:\s*/i, '').trim()
    } else {
      enFunc = rawFn
    }
  }

  const cnChips = cnFn
    ? cnFn.split(/[、，,；;]+/).map(s => s.trim()).filter(Boolean)
    : []

  const nature = h.nature || sup.nature || ''
  const flavorRaw = h.flavor || sup.flavor || ''
  const flavors = flavorRaw
    .split(/[、，,\s]+/)
    .map(s => s.trim())
    .filter(Boolean)

  const meridianRaw = h.meridians || sup.meridians || ''
  const meridians = meridianRaw
    .split(/[、，,\s]+/)
    .map(s => s.trim())
    .filter(Boolean)
    .map(m => (m.endsWith('经') ? m : `${m}经`))

  const category = h.category || sup.category || ''

  return {
    ...h,
    category,
    nature,
    flavors,
    meridians,
    cnFn,
    cnChips,
    cnSrc,
    enFunc,
    enIndic,
    hasEnRaw: Boolean(enFunc || enIndic),
  }
}
